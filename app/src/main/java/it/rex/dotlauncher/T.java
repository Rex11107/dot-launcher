    static String t(String s) {
        if (!en || s == null) return s;
        String r = EN.get(s);
        return r == null ? s : r;
    }

    /** Testo che dipende da un numero: {@code one} per 1, {@code many} per gli altri. */
    static String n(long n, String one, String many) {
        if (n == 1 && en) {
            String r = EN_ONE.get(one);
            if (r != null) return r;
        }
        return t(n == 1 ? one : many);
    }

